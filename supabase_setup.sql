-- Stella Survival shared voting database
create table if not exists public.app_state (
  id integer primary key check (id = 1),
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  voter_id text not null,
  trainee_id bigint not null,
  created_at timestamptz not null default now(),
  vote_date date not null default ((now() at time zone 'Asia/Seoul')::date)
);

-- Upgrade an existing installation without deleting its vote history.
alter table public.votes add column if not exists vote_date date;
update public.votes set vote_date = (created_at at time zone 'Asia/Seoul')::date where vote_date is null;
alter table public.votes alter column vote_date set default ((now() at time zone 'Asia/Seoul')::date);
alter table public.votes alter column vote_date set not null;
alter table public.votes drop constraint if exists votes_one_per_trainee_per_voter;
create unique index if not exists votes_one_per_trainee_per_voter_day on public.votes(voter_id, trainee_id, vote_date);
create index if not exists votes_voter_id_idx on public.votes(voter_id);
create index if not exists votes_trainee_id_idx on public.votes(trainee_id);
create index if not exists votes_vote_date_idx on public.votes(vote_date);

-- Browser clients must not access these tables directly. The Cloudflare Pages Function
-- uses the service-role key kept only in Netlify environment variables.
alter table public.app_state enable row level security;
alter table public.votes enable row level security;
revoke all on public.app_state from anon, authenticated;
revoke all on public.votes from anon, authenticated;
